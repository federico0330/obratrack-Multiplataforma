package com.unaj.obratrack.domain.model

import com.unaj.obratrack.domain.model.TareaPlantilla.*

/** Tareas habituales de cada tipo de obra, en el orden en que suelen hacerse. */
object PlantillasDeTareas {
    fun para(tipo: TipoObra): List<TareaPlantilla> = when (tipo) {
        TipoObra.CASA_NUEVA -> listOf(
            PLANOS_Y_PERMISOS, LIMPIEZA_DEL_TERRENO, REPLANTEO, EXCAVACION, FUNDACIONES, ESTRUCTURA_RESISTENTE,
            MUROS, CUBIERTA, INSTALACION_ELECTRICA, INSTALACION_SANITARIA, INSTALACION_GAS, CLIMATIZACION,
            REVOQUES, CONTRAPISOS, ABERTURAS, PISOS, REVESTIMIENTOS, CARPINTERIA_INTERIOR, HERRERIA,
            ARTEFACTOS_Y_GRIFERIA, ARTEFACTOS_DE_ILUMINACION, PINTURA_INTERIOR, PINTURA_EXTERIOR,
            LIMPIEZA_FINAL, RECEPCION_Y_ENTREGA,
        )
        TipoObra.AMPLIACION -> listOf(
            PLANOS_Y_PERMISOS, REPLANTEO, EXCAVACION, FUNDACIONES, ESTRUCTURA_RESISTENTE, MUROS, CUBIERTA,
            INSTALACION_ELECTRICA, INSTALACION_SANITARIA, REVOQUES, CONTRAPISOS, ABERTURAS, PISOS,
            PINTURA_INTERIOR, PINTURA_EXTERIOR, LIMPIEZA_FINAL,
        )
        TipoObra.REFORMA_INTEGRAL -> listOf(
            PLANOS_Y_PERMISOS, DEMOLICION, RETIRO_DE_ESCOMBROS, INSTALACION_ELECTRICA, INSTALACION_SANITARIA,
            INSTALACION_GAS, CLIMATIZACION, REVOQUES, CONTRAPISOS, IMPERMEABILIZACION, PISOS, REVESTIMIENTOS,
            ABERTURAS, CARPINTERIA_INTERIOR, MUEBLES_A_MEDIDA, ARTEFACTOS_Y_GRIFERIA, ARTEFACTOS_DE_ILUMINACION,
            PINTURA_INTERIOR, LIMPIEZA_FINAL, RECEPCION_Y_ENTREGA,
        )
        TipoObra.BANO -> listOf(
            DEMOLICION, RETIRO_DE_ESCOMBROS, INSTALACION_SANITARIA, INSTALACION_ELECTRICA, IMPERMEABILIZACION,
            CONTRAPISOS, REVESTIMIENTOS, PISOS, ARTEFACTOS_Y_GRIFERIA, MUEBLES_A_MEDIDA, PINTURA_INTERIOR,
            LIMPIEZA_FINAL,
        )
        TipoObra.COCINA -> listOf(
            DEMOLICION, RETIRO_DE_ESCOMBROS, INSTALACION_ELECTRICA, INSTALACION_SANITARIA, INSTALACION_GAS,
            REVESTIMIENTOS, PISOS, MUEBLES_A_MEDIDA, ARTEFACTOS_DE_ILUMINACION, PINTURA_INTERIOR, LIMPIEZA_FINAL,
        )
        TipoObra.PINTURA -> listOf(REVOQUES, PINTURA_INTERIOR, PINTURA_EXTERIOR, LIMPIEZA_FINAL)
    }
}
